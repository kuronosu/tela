package main

import (
	"bytes"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func writeSVGs(t *testing.T, files map[string]string) string {
	t.Helper()
	dir := t.TempDir()
	for name, data := range files {
		p := filepath.Join(dir, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(data), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

const (
	checkSVG  = "<!-- c -->\n<svg class=\"lucide\" xmlns=\"http://www.w3.org/2000/svg\" width=\"24\" height=\"24\" viewBox=\"0 0 24 24\"\n  fill=\"none\" stroke=\"currentColor\">\n  <path d=\"M20 6 9 17l-5-5\" />\n</svg>\n"
	brokenSVG = "<svg><path></svg>"
)

func TestIconsGenWritesFile(t *testing.T) {
	src := writeSVGs(t, map[string]string{"check.svg": checkSVG, "arrow-up.svg": checkSVG, "notes.txt": "x"})
	licensePath := filepath.Join(t.TempDir(), "LICENSE")
	if err := os.WriteFile(licensePath, []byte("ISC License\n\nCopyright (c) Me\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	out := filepath.Join(t.TempDir(), "nested", "out")
	var stdout, stderr bytes.Buffer
	code := run([]string{"icons", "gen", src, "-pkg", "demo", "-o", out, "-source", "Demo 1.0", "-license", "ISC", "-license-file", licensePath}, &stdout, &stderr)
	if code != 0 {
		t.Fatalf("exit %d: %s", code, stderr.String())
	}
	if !strings.Contains(stdout.String(), "2 icons") {
		t.Errorf("stdout: %q", stdout.String())
	}
	data, err := os.ReadFile(filepath.Join(out, "icons_gen.go"))
	if err != nil {
		t.Fatal(err)
	}
	if _, err := parser.ParseFile(token.NewFileSet(), "icons_gen.go", data, parser.ParseComments); err != nil {
		t.Fatalf("the generated file does not parse: %v", err)
	}
	for _, want := range []string{
		"// Code generated by tela icons gen; DO NOT EDIT.",
		"// Source: Demo 1.0",
		"// License: ISC",
		"// Copyright (c) Me",
		"package demo",
		"var ArrowUp = tela.Icon{SVG: `<svg xmlns=",
		"var Check = tela.Icon{SVG: `<svg xmlns=",
		"// Check is the icon \"check\".",
	} {
		if !strings.Contains(string(data), want) {
			t.Errorf("the file lacks %q:\n%s", want, data)
		}
	}
	if strings.Contains(string(data), "<!--") || strings.Contains(string(data), "lucide") {
		t.Errorf("the SVG was not minified:\n%s", data)
	}
}

func TestIconsGenNoMinify(t *testing.T) {
	src := writeSVGs(t, map[string]string{"check.svg": checkSVG})
	out := t.TempDir()
	var stdout, stderr bytes.Buffer
	if code := run([]string{"icons", "gen", "-pkg", "demo", "-minify=false", "-o", out, src}, &stdout, &stderr); code != 0 {
		t.Fatalf("exit %d: %s", code, stderr.String())
	}
	data, _ := os.ReadFile(filepath.Join(out, "icons_gen.go"))
	if !strings.Contains(string(data), "lucide") || !strings.Contains(string(data), "\n  <path") {
		t.Errorf("the SVG was minified:\n%s", data)
	}
}

func TestIconsGenInvalidFiles(t *testing.T) {
	src := writeSVGs(t, map[string]string{"check.svg": checkSVG, "broken.svg": brokenSVG})
	out := t.TempDir()
	var stdout, stderr bytes.Buffer
	if code := run([]string{"icons", "gen", "-pkg", "demo", "-o", out, src}, &stdout, &stderr); code != 1 {
		t.Fatalf("exit %d, want 1", code)
	}
	if !strings.Contains(stderr.String(), "broken.svg") || !strings.Contains(stderr.String(), "-skip-invalid") {
		t.Errorf("stderr: %q", stderr.String())
	}
	if _, err := os.Stat(filepath.Join(out, "icons_gen.go")); err == nil {
		t.Error("a file was written despite the error")
	}
	stdout.Reset()
	stderr.Reset()
	if code := run([]string{"icons", "gen", "-pkg", "demo", "-o", out, "-skip-invalid", src}, &stdout, &stderr); code != 0 {
		t.Fatalf("exit %d: %s", code, stderr.String())
	}
	if !strings.Contains(stderr.String(), "skipped") || !strings.Contains(stderr.String(), "broken.svg") || !strings.Contains(stdout.String(), "1 icons, 1 skipped") {
		t.Errorf("stdout %q stderr %q", stdout.String(), stderr.String())
	}
}

func TestIconsGenRecursiveAndAffixes(t *testing.T) {
	src := writeSVGs(t, map[string]string{"a.svg": checkSVG, "solid/b.svg": checkSVG})
	out := t.TempDir()
	var stdout, stderr bytes.Buffer
	if code := run([]string{"icons", "gen", "-pkg", "demo", "-r", "-prefix", "Icon", "-suffix", "X", "-o", out, src}, &stdout, &stderr); code != 0 {
		t.Fatalf("exit %d: %s", code, stderr.String())
	}
	data, _ := os.ReadFile(filepath.Join(out, "icons_gen.go"))
	for _, want := range []string{"var IconAX =", "var IconSolidBX =", `is the icon "solid/b"`} {
		if !strings.Contains(string(data), want) {
			t.Errorf("the file lacks %q", want)
		}
	}
}

func TestIconsGenUsageErrors(t *testing.T) {
	src := writeSVGs(t, map[string]string{"a.svg": checkSVG})
	for _, tc := range []struct {
		args []string
		code int
		want string
	}{
		{[]string{"icons"}, 2, "Usage"},
		{[]string{"icons", "nope"}, 2, "unknown command"},
		{[]string{"icons", "gen"}, 2, "missing <dir>"},
		{[]string{"icons", "gen", src}, 2, "missing -pkg"},
		{[]string{"icons", "gen", "-pkg", "x", src, src}, 2, "expected one <dir>"},
		{[]string{"icons", "gen", "-pkg", "x", "-bogus", src}, 2, "tela help icons gen"},
		{[]string{"icons", "gen", "-pkg", "x", "-o", "", src}, 2, "empty -o"},
		{[]string{"icons", "gen", "-pkg", "1x", src}, 1, "invalid package name"},
		{[]string{"icons", "gen", "-pkg", "x", "-prefix", "icon", src}, 1, "invalid -prefix"},
		{[]string{"icons", "gen", "-pkg", "x", filepath.Join(src, "missing")}, 1, "cannot read <dir>"},
		{[]string{"icons", "gen", "-pkg", "x", filepath.Join(src, "a.svg")}, 1, "not a directory"},
		{[]string{"icons", "gen", "-pkg", "x", "-license-file", filepath.Join(src, "none"), src}, 1, "-license-file"},
		{[]string{"icons", "gen", "-pkg", "x", t.TempDir()}, 1, "no .svg files"},
	} {
		var stdout, stderr bytes.Buffer
		code := run(tc.args, &stdout, &stderr)
		if code != tc.code || !strings.Contains(stderr.String(), tc.want) {
			t.Errorf("%v: exit %d, stderr %q; want exit %d and %q", tc.args, code, stderr.String(), tc.code, tc.want)
		}
	}
}

func TestIconsHelp(t *testing.T) {
	for _, args := range [][]string{{"help", "icons", "gen"}, {"icons", "help", "gen"}, {"icons", "gen", "-h"}} {
		var stdout, stderr bytes.Buffer
		if code := run(args, &stdout, &stderr); code != 0 || !strings.Contains(stdout.String(), "-license-file") {
			t.Errorf("%v: exit %d, stdout %q, stderr %q", args, code, stdout.String(), stderr.String())
		}
	}
	var stdout, stderr bytes.Buffer
	if code := run([]string{"help"}, &stdout, &stderr); code != 0 || !strings.Contains(stdout.String(), "icons") {
		t.Errorf("tela help lacks icons:\n%s", stdout.String())
	}
	stdout.Reset()
	if code := run([]string{"help", "icons"}, &stdout, &stderr); code != 0 || !strings.Contains(stdout.String(), "tela icons gen") {
		t.Errorf("tela help icons:\n%s", stdout.String())
	}
}
