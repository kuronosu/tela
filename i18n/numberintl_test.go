// maxfrac=0") into options, named after Intl's.
func intlOptions(t *testing.T, spec string) []NumberOption {
	t.Helper()
	var opts []NumberOption
	for _, f := range strings.Fields(spec) {
		k, v, _ := strings.Cut(f, "=")
		switch k {
		case "percent":
			opts = append(opts, Percent())
		case "currency":
			opts = append(opts, Currency(v))
		case "display":
			opts = append(opts, CurrencyDisplay(map[string]CurrencyDisplayMode{"code": CurrencyCode, "name": CurrencyName, "narrow": CurrencyNarrowSymbol}[v]))
		case "accounting":
			opts = append(opts, CurrencySign(CurrencySignAccounting))
		case "sign":
			opts = append(opts, SignDisplay(map[string]SignDisplayMode{"always": SignAlways, "exceptZero": SignExceptZero, "negative": SignNegative, "never": SignNever}[v]))
		case "compact":
			opts = append(opts, Notation(NotationCompact))
			if v == "long" {
				opts = append(opts, CompactDisplay(CompactLong))
			}
		case "scientific":
			opts = append(opts, Notation(NotationScientific))
		case "engineering":
			opts = append(opts, Notation(NotationEngineering))
		case "maxfrac":
			n, _ := strconv.Atoi(v)
			opts = append(opts, MaxFractionDigits(n))
		case "minfrac":
			n, _ := strconv.Atoi(v)
			opts = append(opts, MinFractionDigits(n))
		default:
			t.Fatalf("spec %q: unknown %q", spec, f)
		}
	}
	return opts
}

func TestNumbersMatchIntl(t *testing.T) {
	for _, c := range intlNumbers {
		if got := For(c.loc).Number(c.v, intlOptions(t, c.spec)...); got != c.want {
			t.Errorf("For(%q).Number(%v, %s) = %q, want Intl's %q", c.loc, c.v, c.spec, got, c.want)
		}
	}
}
