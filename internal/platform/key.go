// KeyEvent is a key press, repeat or release, delivered to the focused
// window. Following winit (ADR-021), it describes the key three ways, and
// each serves a different purpose:
//
//   - Code, the physical key: layout-independent position. For shortcuts
//     that depend on position (WASD in games, the key under Escape).
//   - Key, the logical key: what the key means with the active layout and
//     modifiers. For shortcuts by meaning (Ctrl+Z is Key "z" on QWERTY,
//     AZERTY and Dvorak alike) and for non-text keys (Enter, ArrowLeft).
//   - Text, the produced text. For text input; it is what a text field
//     inserts.
//
// See the package documentation ("Keyboard") for the delivery contract:
// repeats, focus changes and ordering.
type KeyEvent struct {
	Action KeyAction
	// Code is the physical key.
	Code KeyCode
	// Key is the logical key: a W3C UI Events "key" value. It reflects
	// every active modifier and lock (Shift, AltGr, Caps Lock, Num Lock)
	// except Ctrl, like winit's logical_key: Ctrl+Shift+A has Key "A".
	// A dead key (a pending accent) is KeyDead.
	Key Key
	// Text is the text the press produces with the same modifiers as Key
	// (so Ctrl+C has Text "c", like winit's text; Ctrl never turns it into
	// a control character). It is empty for releases, for keys that
	// produce no text (modifiers, arrows, function keys), for dead keys,
	// and for keys whose only text would be a control character (Enter,
	// Tab, Backspace, Escape, Delete): those are handled by Key, not
	// inserted as text. During a dead-key or compose sequence the
	// intermediate presses have empty Text and the final one carries the
	// composed text ("é").
	//
	// Text is not a decision about text input: whether Ctrl+C, Alt+X or
	// Super+V inserts its Text is up to the layers above, which insert it
	// only when neither Ctrl nor Super is held (AltGr is never reported
	// as Ctrl or Alt; see Modifiers).
	Text string
	// Location distinguishes keys with the same meaning: left and right
	// modifiers, numpad digits and operators (Code.Location()).
	Location KeyLocation
	// Repeat marks a press generated by key repeat while the key is held.
	// Only presses repeat; there is no release between repeats.
	Repeat bool
	// Synthetic marks a release the backend generated because the window
	// lost focus while the key was held (see the package documentation).
	// It ends the key's press but must not trigger actions (a button must
	// not activate on a synthetic Space release).
	Synthetic bool
	// Mods is the modifier state after this event: the press of ShiftLeft
	// has ModShift, its release does not (like the DOM's shiftKey).
	Mods Modifiers
	// Time is when the event happened, in the time base of [Backend.Now].
	Time time.Duration
}

// KeyAction is what happened to a key in a [KeyEvent].
type KeyAction uint8

const (
	// KeyPress: the key went down, or repeats while held (Repeat).
	KeyPress KeyAction = iota
	// KeyRelease: the key went up.
	KeyRelease
)

func (a KeyAction) String() string {
	switch a {
	case KeyPress:
		return "press"
	case KeyRelease:
		return "release"
	}
	return "KeyAction(invalid)"
}

// KeyLocation tells keys with the same logical meaning apart, with the
// values of the DOM's KeyboardEvent.location.
type KeyLocation uint8

const (
	KeyLocationStandard KeyLocation = iota // any key not listed below
	KeyLocationLeft                        // left Shift, Ctrl, Alt, Meta
	KeyLocationRight                       // right Shift, Ctrl, Alt (AltGr), Meta
	KeyLocationNumpad                      // numeric keypad
)

var keyLocationNames = [...]string{"standard", "left", "right", "numpad"}

func (l KeyLocation) String() string {
	if int(l) < len(keyLocationNames) {
		return keyLocationNames[l]
	}
	return "KeyLocation(invalid)"
}

// Key is a logical key: a W3C UI Events KeyboardEvent "key" value
// (https://www.w3.org/TR/uievents-key/), which is also what a browser
// reports as KeyboardEvent.key. It is either a named key (the Key*
// constants: "Enter", "ArrowLeft", "Shift", "Dead") or a character string:
// the character the key produces with the active layout and modifiers
// except Ctrl ("a", "A", "é", "1", "!", and " " for the space bar, which
// W3C treats as a character, unlike winit's NamedKey::Space).
//
// Comparing with a constant or a literal works for both kinds:
// e.Key == KeyEscape, e.Key == "z".
type Key string

// IsNamed reports whether k is one of the named key values (a Key*
// constant) rather than a character.
func (k Key) IsNamed() bool {
	_, ok := namedKeys()[k]
	return ok
}

