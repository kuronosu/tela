//go:build ignore

// gen_keysyms generates keysyms_table.go from libxkbcommon's
// xkbcommon-keysyms.h: the keysym names (with their aliases) and the
// Unicode mapping of the legacy keysyms, both taken from the header's
// machine-readable lines (see the header's own description of their
// format). Run it with go generate; the header path defaults to the system
// copy installed with the libxkbcommon development files.
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

var (
	header = flag.String("header", "/usr/include/xkbcommon/xkbcommon-keysyms.h", "path of xkbcommon-keysyms.h")
	out    = flag.String("o", "keysyms_table.go", "output file")
)

var defineRE = regexp.MustCompile(`^#define XKB_KEY_([a-zA-Z_0-9]+)\s+0x([0-9a-f]+)\s*(?:/\*(.*)\*/)?\s*$`)
var ucsRE = regexp.MustCompile(`^\s*(\(|<)?U\+([0-9A-F]{4,6}) `)

// vendorUCSRE finds the character of a vendor keysym (XF86Numeric0 …),
// whose comment starts with the kernel version and code.
var vendorUCSRE = regexp.MustCompile(`<U\+([0-9A-F]{4,6}) `)

// ucsOverrides are mappings where libxkbcommon's keysym-utf.c differs
// from the header's annotation: it uses the canonical equivalents of the
// deprecated angle brackets U+2329 and U+232A.
var ucsOverrides = map[uint32]uint32{0x0abc: 0x27e8, 0x0abe: 0x27e9}

type name struct {
	name string
	sym  uint32
}

func main() {
	flag.Parse()
	data, err := os.ReadFile(*header)
	if err != nil {
		log.Fatal(err)
	}
	var names []name
	ucs := map[uint32]uint32{}
	var ucsOrder []uint32
	var notice []string
	inNotice := false
	sc := bufio.NewScanner(bytes.NewReader(data))
	for sc.Scan() {
		line := sc.Text()
		// The copyright notice block of the header.
		if strings.HasPrefix(line, "/****") && !inNotice && len(notice) == 0 {
			inNotice = true
			continue
		}
		if inNotice {
			if strings.HasPrefix(line, "****") {
				inNotice = false
				continue
			}
			notice = append(notice, line)
			continue
		}
		m := defineRE.FindStringSubmatch(line)
		if m == nil {
			continue
		}
		v, err := strconv.ParseUint(m[2], 16, 32)
		if err != nil {
			log.Fatalf("%s: %v", line, err)
		}
		sym := uint32(v)
		names = append(names, name{m[1], sym})
		if sym >= 0x10000000 {
			if u := vendorUCSRE.FindStringSubmatch(m[3]); u != nil {
				cp, _ := strconv.ParseUint(u[1], 16, 32)
				if _, ok := ucs[sym]; !ok {
					ucs[sym] = uint32(cp)
					ucsOrder = append(ucsOrder, sym)
				}
			}
			continue
		}
		u := ucsRE.FindStringSubmatch(m[3])
		if u == nil || u[1] == "<" {
			// "<U+...>" marks a more specific keysym of a character
			// (KP_Space, KP_0, …): ToUTF32 handles those by rule.
			continue
		}
		cp, _ := strconv.ParseUint(u[2], 16, 32)
		if o, ok := ucsOverrides[sym]; ok {
			cp = uint64(o)
		}
		if sym < 0x100 || sym >= 0x01000000 || (sym >= 0xff00 && sym <= 0xffff) {
			continue // Latin-1, Unicode and function keysyms: by rule
		}
		if _, ok := ucs[sym]; !ok {
			ucs[sym] = uint32(cp)
			ucsOrder = append(ucsOrder, sym)
		}
	}
	if err := sc.Err(); err != nil {
		log.Fatal(err)
	}
	if len(notice) == 0 {
		log.Fatal("copyright notice not found in the header")
	}

	// Canonical names: the first name listed for each value.
	canonical := map[uint32]string{}
	for _, n := range names {
		if _, ok := canonical[n.sym]; !ok {
			canonical[n.sym] = n.name
		}
	}
	byName := append([]name(nil), names...)
	sort.SliceStable(byName, func(i, j int) bool { return byName[i].name < byName[j].name })
	sort.Slice(ucsOrder, func(i, j int) bool { return ucsOrder[i] < ucsOrder[j] })

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by gen_keysyms.go from xkbcommon-keysyms.h; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "// The keysym names and their Unicode mappings come from libxkbcommon's\n")
	fmt.Fprintf(&b, "// xkbcommon-keysyms.h (derived from X11's keysymdef.h), which carries the\n")
	fmt.Fprintf(&b, "// following notice:\n//\n")
	for _, l := range notice {
		fmt.Fprintf(&b, "//\t%s\n", strings.TrimRight(l, " "))
	}
	fmt.Fprintf(&b, "\npackage xkb\n\n")
	fmt.Fprintf(&b, "// keysymNames lists every keysym name of the header, sorted by name.\n")
	fmt.Fprintf(&b, "var keysymNames = [...]keysymName{\n")
	for _, n := range byName {
		fmt.Fprintf(&b, "\t{%q, %#x},\n", n.name, n.sym)
	}
	fmt.Fprintf(&b, "}\n\n")

	syms := make([]uint32, 0, len(canonical))
	for s := range canonical {
		syms = append(syms, s)
	}
	sort.Slice(syms, func(i, j int) bool { return syms[i] < syms[j] })
	fmt.Fprintf(&b, "// keysymCanonical gives the canonical (first listed) name of each named\n// keysym, sorted by keysym.\n")
	fmt.Fprintf(&b, "var keysymCanonical = [...]keysymName{\n")
	for _, s := range syms {
		fmt.Fprintf(&b, "\t{%q, %#x},\n", canonical[s], s)
	}
	fmt.Fprintf(&b, "}\n\n")

	fmt.Fprintf(&b, "// legacyUCS maps the legacy keysyms (outside Latin-1, the function keys\n// and the Unicode range) to Unicode, sorted by keysym.\n")
	fmt.Fprintf(&b, "var legacyUCS = [...][2]uint32{\n")
	for _, s := range ucsOrder {
		fmt.Fprintf(&b, "\t{%#x, %#x},\n", s, ucs[s])
	}
	fmt.Fprintf(&b, "}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}
