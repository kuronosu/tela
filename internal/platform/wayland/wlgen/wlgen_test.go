// TELA_UPDATE=1 rewrites the golden file (ADR-022).
func updating() bool { return os.Getenv("TELA_UPDATE") == "1" }

func TestGolden(t *testing.T) {
	protos, err := loadProtocols([]string{filepath.Join("testdata", "test_protocol.xml")})
	if err != nil {
		t.Fatal(err)
	}
	files, err := generate(protos, "protocols")
	if err != nil {
		t.Fatal(err)
	}
	if len(files) != 1 {
		t.Fatalf("generated %d files, want 1", len(files))
	}
	got := files["test_protocol.go"]
	golden := filepath.Join("testdata", "test_protocol.go.golden")
	if updating() {
		if err := os.WriteFile(golden, got, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(golden)
	if err != nil {
		t.Fatalf("%v (run TELA_UPDATE=1 go test ./internal/platform/wayland/wlgen/ to create it)", err)
	}
	if !bytes.Equal(got, want) {
		actual := golden + ".actual"
		os.WriteFile(actual, got, 0o644)
		t.Errorf("generated code differs from %s; diff it against %s, and if the change is intended run TELA_UPDATE=1 go test ./internal/platform/wayland/wlgen/",
			golden, actual)
	} else {
		os.Remove(golden + ".actual")
	}
}

