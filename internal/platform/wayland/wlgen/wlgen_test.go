// The checked-in bindings must be exactly what the generator produces now, so
// a changed XML file or generator without a `go generate` fails the build.
func TestCheckedInBindingsAreFresh(t *testing.T) {
	protoDir := filepath.Join("..", "protocols")
	protos, err := loadProtocols([]string{filepath.Join(protoDir, "xml")})
	if err != nil {
		t.Fatal(err)
	}
	files, err := generate(protos, "protocols")
	if err != nil {
		t.Fatal(err)
	}

	// Write to a temp dir through the same path the CLI uses, then compare.
	tmp := t.TempDir()
	if err := run([]string{"-out", tmp, filepath.Join(protoDir, "xml")}); err != nil {
		t.Fatal(err)
	}

	var names []string
	for name := range files {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		fresh, err := os.ReadFile(filepath.Join(tmp, name))
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(fresh, files[name]) {
			t.Errorf("%s: the CLI output differs from generate()", name)
		}
		checked, err := os.ReadFile(filepath.Join(protoDir, name))
		if err != nil {
			t.Errorf("%s is missing from internal/platform/wayland/protocols; run go generate ./internal/platform/wayland/...", name)
			continue
		}
		if !bytes.Equal(checked, fresh) {
			t.Errorf("%s is stale; run go generate ./internal/platform/wayland/...", name)
		}
	}

	// No orphaned generated files either (a protocol removed from xml/).
	entries, _ := os.ReadDir(protoDir)
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".go") {
			continue
		}
		if _, ok := files[e.Name()]; ok {
			continue
		}
		src, _ := os.ReadFile(filepath.Join(protoDir, e.Name()))
		if bytes.Contains(src[:min(len(src), 200)], []byte("Code generated by wlgen")) {
			t.Errorf("%s is generated but no XML produces it any more; delete it", e.Name())
		}
	}
}

func TestGenerateIsDeterministic(t *testing.T) {
	protos, err := loadProtocols([]string{filepath.Join("..", "protocols", "xml")})
	if err != nil {
		t.Fatal(err)
	}
	a, err := generate(protos, "protocols")
	if err != nil {
		t.Fatal(err)
	}
	protos2, _ := loadProtocols([]string{filepath.Join("..", "protocols", "xml")})
	b, err := generate(protos2, "protocols")
	if err != nil {
		t.Fatal(err)
	}
	for name := range a {
		if !bytes.Equal(a[name], b[name]) {
			t.Errorf("%s differs between two runs", name)
		}
	}
}

func generateXML(t *testing.T, docs ...string) error {
	t.Helper()
	dir := t.TempDir()
	for i, d := range docs {
		name := filepath.Join(dir, string(rune('a'+i))+".xml")
		if err := os.WriteFile(name, []byte(d), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	protos, err := loadProtocols([]string{dir})
	if err != nil {
		return err
	}
	_, err = generate(protos, "protocols")
	return err
}

func TestGeneratorErrors(t *testing.T) {
	cases := []struct {
		name string
		xml  string
		want string
	}{
		{"unknown enum", `<protocol name="p"><interface name="a" version="1">
			<request name="r"><arg name="x" type="uint" enum="nope"/></request></interface></protocol>`,
			`unknown enum "nope"`},
		{"unknown interface", `<protocol name="p"><interface name="a" version="1">
			<request name="r"><arg name="x" type="object" interface="ghost"/></request></interface></protocol>`,
			`interface "ghost", which no loaded protocol defines`},
		{"bad type", `<protocol name="p"><interface name="a" version="1">
			<request name="r"><arg name="x" type="float"/></request></interface></protocol>`,
			`unknown argument type "float"`},
		{"bad enum value", `<protocol name="p"><interface name="a" version="1">
			<enum name="e"><entry name="x" value="-1"/></enum></interface></protocol>`,
			`not an unsigned 32-bit number`},
		{"identifier collision", `<protocol name="p"><interface name="a_b" version="1"/><interface name="a" version="1">
			<enum name="b_x"><entry name="v" value="0"/></enum></interface>
			<interface name="a_b_x" version="1"/></protocol>`,
			`generated twice`},
		{"reserved method", `<protocol name="p"><interface name="a" version="1">
			<request name="destroyed"/></interface></protocol>`,
			`wire.Proxy.Destroyed`},
		{"two new_ids", `<protocol name="p"><interface name="a" version="1">
			<request name="r"><arg name="x" type="new_id" interface="a"/><arg name="y" type="new_id" interface="a"/></request></interface></protocol>`,
			`more than one new_id`},
		{"no name", `<protocol><interface name="a" version="1"/></protocol>`, `no name`},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			err := generateXML(t, c.xml)
			if err == nil || !strings.Contains(err.Error(), c.want) {
				t.Errorf("error = %v, want it to contain %q", err, c.want)
			}
		})
	}
}

func TestNaming(t *testing.T) {
	for in, want := range map[string]string{
		"wl_surface":                "WlSurface",
		"wp_cursor_shape_device_v1": "WpCursorShapeDeviceV1",
		"zwp_text_input_v3":         "ZwpTextInputV3",
		"90":                        "90",
		"flipped_90":                "Flipped90",
	} {
		if got := camel(in); got != want {
			t.Errorf("camel(%q) = %q, want %q", in, got, want)
		}
	}
	for in, want := range map[string]string{
		"x_dest":    "xDest",
		"type":      "type_",
		"interface": "interface_",
		"self":      "self_",
		"id":        "id",
		"version":   "version_",
	} {
		if got := paramName(in); got != want {
			t.Errorf("paramName(%q) = %q, want %q", in, got, want)
		}
	}
}

