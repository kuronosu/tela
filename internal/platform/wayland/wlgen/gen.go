package main

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"go/scanner"
	"strconv"
	"strings"
)

const wirePkg = "github.com/kuronosu/tela/internal/platform/wayland/wire"

// generator holds the cross-protocol symbol tables. All protocols end up in one
// Go package, so interfaces and enums may reference each other freely.
type generator struct {
	pkg    string
	ifaces map[string]*iface
	enums  map[string]string // "interface.enum" -> Go type name
	idents map[string]string // package-level Go identifier -> where it comes from
}

// generate produces one Go file per protocol. The result maps file name to
// formatted source. Output is a pure function of the input.
func generate(protos []*protocol, pkg string) (map[string][]byte, error) {
	g := &generator{
		pkg:    pkg,
		ifaces: map[string]*iface{},
		enums:  map[string]string{},
		idents: map[string]string{},
	}
	for _, p := range protos {
		for _, i := range p.Interfaces {
			if _, dup := g.ifaces[i.Name]; dup {
				return nil, fmt.Errorf("%s: interface %s is defined twice", p.File, i.Name)
			}
			g.ifaces[i.Name] = i
			for _, e := range i.Enums {
				g.enums[i.Name+"."+e.Name] = camel(i.Name) + camel(e.Name)
			}
		}
	}
	out := map[string][]byte{}
	for _, p := range protos {
		src, err := g.protocolFile(p)
		if err != nil {
			return nil, err
		}
		formatted, err := format.Source(src)
		if err != nil {
			return nil, fmt.Errorf("%s: generated code does not parse: %w\n%s", p.File, err, numbered(src, err))
		}
		name := strings.ReplaceAll(p.Name, "-", "_") + ".go"
		if _, dup := out[name]; dup {
			return nil, fmt.Errorf("%s: two protocols are named %q", p.File, p.Name)
		}
		out[name] = formatted
	}
	return out, nil
}

// numbered renders the source lines around the first syntax error, for the
// "generated code does not parse" diagnostic.
func numbered(src []byte, err error) string {
	at := 1
	var list scanner.ErrorList
	if errors.As(err, &list) && len(list) > 0 {
		at = list[0].Pos.Line
	}
	var b strings.Builder
	for i, l := range strings.Split(string(src), "\n") {
		if i+1 >= at-8 && i+1 <= at+8 {
			fmt.Fprintf(&b, "%5d  %s\n", i+1, l)
		}
	}
	return b.String()
}

// claim registers a package-level identifier and fails on collisions.
func (g *generator) claim(ident, what string) error {
	if prev, ok := g.idents[ident]; ok {
		return fmt.Errorf("Go identifier %s is generated twice (%s and %s); rename one in the generator", ident, prev, what)
	}
	g.idents[ident] = what
	return nil
}

// file accumulates the source of one generated file.
type file struct {
	b       bytes.Buffer
	usesFmt bool
}

func (f *file) p(format string, args ...any) {
	fmt.Fprintf(&f.b, format, args...)
	f.b.WriteByte('\n')
}

// doc writes a doc comment. An empty string is a blank comment line.
func (f *file) doc(indent string, lines []string) {
	for _, l := range lines {
		if l == "" {
			f.p("%s//", indent)
		} else {
			f.p("%s// %s", indent, l)
		}
	}
}

// descLines turns a <description> body into trimmed comment lines.
func descLines(d *description) []string {
	if d == nil {
		return nil
	}
	var lines []string
	blank := true // swallow leading blank lines
	for _, l := range strings.Split(d.Text, "\n") {
		l = strings.TrimSpace(l)
		if l == "" {
			if !blank {
				lines = append(lines, "")
			}
			blank = true
			continue
		}
		lines = append(lines, l)
		blank = false
	}
	for len(lines) > 0 && lines[len(lines)-1] == "" {
		lines = lines[:len(lines)-1]
	}
	return lines
}

func summaryOf(d *description) string {
	if d == nil {
		return ""
	}
	return oneLine(d.Summary)
}

// head builds the first doc line "Name <what>: summary." followed by the body.
func head(first, summary string, d *description, extra ...string) []string {
	if summary != "" {
		first += ": " + strings.TrimRight(summary, ".") + "."
	} else {
		first += "."
	}
	lines := []string{first}
	if body := descLines(d); len(body) > 0 {
		lines = append(lines, "")
		lines = append(lines, body...)
	}
	if len(extra) > 0 {
		lines = append(lines, "")
		lines = append(lines, extra...)
	}
	return lines
}

func (g *generator) protocolFile(p *protocol) ([]byte, error) {
	f := &file{}
	var body file

	for _, i := range p.Interfaces {
		if err := g.genInterface(&body, i); err != nil {
			return nil, fmt.Errorf("%s: %w", p.File, err)
		}
	}

	f.p("// Code generated by wlgen from %s. DO NOT EDIT.", p.File)
	f.p("//")
	f.p("// Protocol: %s", p.Name)
	if cr := descLines(&description{Text: p.Copyright}); len(cr) > 0 {
		f.p("//")
		f.doc("", cr)
	}
	f.p("")
	f.p("//go:build linux")
	f.p("")
	f.p("package %s", g.pkg)
	f.p("")
	f.p("import (")
	if body.usesFmt {
		f.p("\t\"fmt\"")
		f.p("")
	}
	f.p("\t%q", wirePkg)
	f.p(")")
	f.p("")
	f.b.Write(body.b.Bytes())
	return f.b.Bytes(), nil
}

// goType returns the Go type of an argument. ctx is the interface the message
// belongs to, used to resolve unqualified enum names.
func (g *generator) goType(a *arg, ctx *iface) (string, error) {
	enumType := ""
	if a.Enum != "" {
		key := a.Enum
		if !strings.Contains(key, ".") {
			key = ctx.Name + "." + key
		}
		t, ok := g.enums[key]
		if !ok {
			return "", fmt.Errorf("%s: argument %q refers to unknown enum %q", ctx.Name, a.Name, a.Enum)
		}
		enumType = t
	}
	switch a.Type {
	case "int":
		if enumType != "" {
			return enumType, nil
		}
		return "int32", nil
	case "uint":
		if enumType != "" {
			return enumType, nil
		}
		return "uint32", nil
	case "fixed":
		return "float64", nil
	case "string":
		if a.nullable() {
			return "*string", nil
		}
		return "string", nil
	case "array":
		return "[]byte", nil
	case "fd":
		return "int", nil
	case "object", "new_id":
		if a.Interface == "" {
			return "wire.Object", nil
		}
		if _, ok := g.ifaces[a.Interface]; !ok {
			return "", fmt.Errorf("%s: argument %q uses interface %q, which no loaded protocol defines; add the XML that defines it",
				ctx.Name, a.Name, a.Interface)
		}
		return "*" + camel(a.Interface), nil
	}
	return "", fmt.Errorf("%s: argument %q has unknown type %q", ctx.Name, a.Name, a.Type)
}

func argTypeConst(t string) (string, error) {
	switch t {
	case "int":
		return "wire.ArgInt", nil
	case "uint":
		return "wire.ArgUint", nil
	case "fixed":
		return "wire.ArgFixed", nil
	case "string":
		return "wire.ArgString", nil
	case "object":
		return "wire.ArgObject", nil
	case "new_id":
		return "wire.ArgNewID", nil
	case "array":
		return "wire.ArgArray", nil
	case "fd":
		return "wire.ArgFd", nil
	}
	return "", fmt.Errorf("unknown argument type %q", t)
}

func (g *generator) genInterface(f *file, i *iface) error {
	T := camel(i.Name)
	desc := "iface" + T
	isDisplay := i.Name == "wl_display"

	for _, id := range []string{T, T + "InterfaceName", T + "Version", desc} {
		if err := g.claim(id, "interface "+i.Name); err != nil {
			return err
		}
	}

	// Type, constants, descriptor.
	f.doc("", head(T+" is the client proxy of the "+i.Name+" interface", summaryOf(i.Description), i.Description,
		fmt.Sprintf("Highest version known to these bindings: %d.", i.Version)))
	f.p("type %s struct {", T)
	f.p("\twire.Proxy")
	if !isDisplay {
		for _, e := range i.Events {
			f.p("\ton%s func(%s)", camel(e.Name), T+camel(e.Name)+"Event")
		}
	}
	f.p("}")
	f.p("")
	f.p("// %sInterfaceName is the protocol name of %s, as advertised by wl_registry.global.", T, T)
	f.p("const %sInterfaceName = %q", T, i.Name)
	f.p("")
	f.p("// %sVersion is the highest version of %s known to these bindings.", T, i.Name)
	f.p("const %sVersion = %d", T, i.Version)
	f.p("")
	f.p("var %s = wire.Interface{", desc)
	f.p("\tName: %q,", i.Name)
	f.p("\tVersion: %d,", i.Version)
	for _, kind := range []struct {
		field string
		msgs  []*message
	}{{"Requests", i.Requests}, {"Events", i.Events}} {
		if len(kind.msgs) == 0 {
			continue
		}
		f.p("\t%s: []wire.Message{", kind.field)
		for _, m := range kind.msgs {
			f.p("\t\t{")
			f.p("\t\t\tName: %q,", m.Name)
			if m.since() > 1 {
				f.p("\t\t\tSince: %d,", m.since())
			}
			if m.Type == "destructor" {
				f.p("\t\t\tDestructor: true,")
			}
			if len(m.Args) > 0 {
				f.p("\t\t\tArgs: []wire.Arg{")
				for _, a := range m.Args {
					tc, err := argTypeConst(a.Type)
					if err != nil {
						return fmt.Errorf("%s.%s: %w", i.Name, m.Name, err)
					}
					line := fmt.Sprintf("{Type: %s, Name: %q", tc, a.Name)
					if a.nullable() {
						line += ", Nullable: true"
					}
					if a.Interface != "" {
						line += fmt.Sprintf(", Interface: %q", a.Interface)
					}
					f.p("\t\t\t\t%s},", line)
				}
				f.p("\t\t\t},")
			}
			f.p("\t\t},")
		}
		f.p("\t},")
	}
	f.p("}")
	f.p("")
	f.p("func init() { wire.Register(&%s) }", desc)
	f.p("")
	f.p("// Descriptor implements wire.Object.")
	f.p("func (self *%s) Descriptor() *wire.Interface { return &%s }", T, desc)
	f.p("")

	if isDisplay {
		f.p("// New%s binds a new wl_display proxy as object 1 of c. The runtime handles", T)
		f.p("// wl_display.error and wl_display.delete_id itself, so the proxy has no event handlers.")
		f.p("func New%s(c *wire.Conn) *%s {", T, T)
		f.p("\td := &%s{}", T)
		f.p("\tc.SetDisplay(d)")
		f.p("\treturn d")
		f.p("}")
		f.p("")
		if err := g.claim("New"+T, "interface "+i.Name); err != nil {
			return err
		}
	}

	for _, e := range i.Enums {
		if err := g.genEnum(f, i, e); err != nil {
			return err
		}
	}

	methods := map[string]string{}
	claimMethod := func(name, what string) error {
		if reservedMethods[name] {
			return fmt.Errorf("%s: %s would shadow wire.Proxy.%s; special-case it in the generator", i.Name, what, name)
		}
		if prev, ok := methods[name]; ok {
			return fmt.Errorf("%s: method %s generated twice (%s and %s)", i.Name, name, prev, what)
		}
		methods[name] = what
		return nil
	}

	if !isDisplay {
		for opcode, e := range i.Events {
			if err := g.genEvent(f, i, e, opcode, claimMethod); err != nil {
				return err
			}
		}
		if err := g.genDispatch(f, i); err != nil {
			return err
		}
	} else {
		f.p("// Dispatch implements wire.Object. wl_display events are handled by the runtime.")
		f.p("func (self *%s) Dispatch(opcode uint16, r *wire.Reader) error {", T)
		f.p("\treturn wire.UnknownEvent(self, opcode)")
		f.p("}")
		f.p("")
	}

	for opcode, m := range i.Requests {
		if err := g.genRequest(f, i, m, opcode, claimMethod); err != nil {
			return err
		}
	}
	return nil
}

func (g *generator) genEnum(f *file, i *iface, e *enum) error {
	T := camel(i.Name) + camel(e.Name)
	if err := g.claim(T, fmt.Sprintf("enum %s.%s", i.Name, e.Name)); err != nil {
		return err
	}
	var extra []string
	if e.Since > 1 {
		extra = append(extra, fmt.Sprintf("Since version %d.", e.Since))
	}
	if e.bitfield() {
		extra = append(extra, "Bitfield: combine values with | and test them with Has.")
	}
	f.doc("", head(T+" is the "+i.Name+"."+e.Name+" enum", summaryOf(e.Description), e.Description, extra...))
	f.p("type %s uint32", T)
	f.p("")
	if len(e.Entries) > 0 {
		f.p("const (")
		for _, en := range e.Entries {
			c := T + camel(en.Name)
			if err := g.claim(c, fmt.Sprintf("enum entry %s.%s.%s", i.Name, e.Name, en.Name)); err != nil {
				return err
			}
			note := ""
			if en.Since > 1 {
				note += fmt.Sprintf(" Since version %d.", en.Since)
			}
			if en.DeprecatedSince > 0 {
				note += fmt.Sprintf(" Deprecated since version %d.", en.DeprecatedSince)
			}
			if s := oneLine(en.Summary); s != "" || note != "" {
				f.p("\t// %s%s", c, entryDoc(s, note))
			}
			f.p("\t%s %s = %s", c, T, en.Value)
		}
		f.p(")")
		f.p("")
	}

	f.usesFmt = true
	if e.bitfield() {
		f.p("// Has reports whether every bit of flags is set in e.")
		f.p("func (e %s) Has(flags %s) bool { return e&flags == flags }", T, T)
		f.p("")
		f.p("// String lists the names of the set flags, separated by \"|\".")
		f.p("func (e %s) String() string {", T)
		zero := "0"
		for _, en := range e.Entries {
			if v, err := strconv.ParseUint(en.Value, 0, 32); err == nil && v == 0 {
				zero = en.Name
				break
			}
		}
		f.p("\tif e == 0 {")
		f.p("\t\treturn %q", zero)
		f.p("\t}")
		f.p("\tvar s string")
		f.p("\trem := e")
		for _, en := range e.Entries {
			if v, err := strconv.ParseUint(en.Value, 0, 32); err == nil && v == 0 {
				continue
			}
			c := T + camel(en.Name)
			f.p("\tif e&%s == %s {", c, c)
			f.p("\t\ts += \"|\" + %q", en.Name)
			f.p("\t\trem &^= %s", c)
			f.p("\t}")
		}
		f.p("\tif rem != 0 {")
		f.p("\t\ts += fmt.Sprintf(\"|%%#x\", uint32(rem))")
		f.p("\t}")
		f.p("\treturn s[1:]")
		f.p("}")
	} else {
		f.p("// String returns the protocol name of the value, or a number if it is unknown.")
		f.p("func (e %s) String() string {", T)
		f.p("\tswitch e {")
		seen := map[string]bool{}
		for _, en := range e.Entries {
			v, _ := strconv.ParseUint(en.Value, 0, 32)
			key := strconv.FormatUint(v, 10)
			if seen[key] {
				continue // duplicate value: keep the first name
			}
			seen[key] = true
			f.p("\tcase %s:", T+camel(en.Name))
			f.p("\t\treturn %q", en.Name)
		}
		f.p("\t}")
		f.p("\treturn fmt.Sprintf(\"%s(%%d)\", uint32(e))", T)
		f.p("}")
	}
	f.p("")
	return nil
}

// oneLine collapses all whitespace runs, so XML summaries that span lines stay
// on one comment line.
func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }

func entryDoc(summary, note string) string {
	s := ":"
	if summary != "" {
		s = ": " + strings.TrimRight(summary, ".") + "."
	}
	return s + note
}

func (g *generator) genEvent(f *file, i *iface, m *message, opcode int, claim func(name, what string) error) error {
	T := camel(i.Name)
	ev := T + camel(m.Name) + "Event"
	setter := "Set" + camel(m.Name) + "Handler"
	if err := g.claim(ev, fmt.Sprintf("event %s.%s", i.Name, m.Name)); err != nil {
		return err
	}
	if err := claim(setter, "event "+m.Name); err != nil {
		return err
	}
	var extra []string
	if m.since() > 1 {
		extra = append(extra, fmt.Sprintf("Since version %d.", m.since()))
	}
	f.doc("", head(ev+" holds the arguments of the "+i.Name+"."+m.Name+" event", summaryOf(m.Description), m.Description, extra...))
	f.p("type %s struct {", ev)
	for _, a := range m.Args {
		t, err := g.goType(a, i)
		if err != nil {
			return err
		}
		if s := oneLine(a.Summary); s != "" {
			f.p("\t// %s: %s.", camel(a.Name), strings.TrimRight(s, "."))
		}
		if a.Type == "fd" {
			f.p("\t// The receiver owns the descriptor and must close it.")
		}
		f.p("\t%s %s", camel(a.Name), t)
	}
	f.p("}")
	f.p("")
	f.p("// %s sets the callback for the %s event. Pass nil to remove it.", setter, m.Name)
	if m.since() > 1 {
		f.p("// The event exists since version %d.", m.since())
	}
	if hasFd(m) {
		f.p("// Without a handler the event's file descriptors are closed.")
	}
	f.p("func (self *%s) %s(h func(%s)) { self.on%s = h }", T, setter, ev, camel(m.Name))
	f.p("")
	return nil
}

func hasFd(m *message) bool {
	for _, a := range m.Args {
		if a.Type == "fd" {
			return true
		}
	}
	return false
}

func (g *generator) genDispatch(f *file, i *iface) error {
	T := camel(i.Name)
	f.p("// Dispatch implements wire.Object: it decodes one event and calls its handler.")
	f.p("func (self *%s) Dispatch(opcode uint16, r *wire.Reader) error {", T)
	if len(i.Events) == 0 {
		f.p("\treturn wire.UnknownEvent(self, opcode)")
		f.p("}")
		f.p("")
		return nil
	}
	f.p("\tswitch opcode {")
	for opcode, m := range i.Events {
		ev := T + camel(m.Name) + "Event"
		f.p("\tcase %d: // %s", opcode, m.Name)
		f.p("\t\tvar ev %s", ev)
		var fds []string
		for _, a := range m.Args {
			field := "ev." + camel(a.Name)
			t, err := g.goType(a, i)
			if err != nil {
				return err
			}
			switch a.Type {
			case "int":
				if t == "int32" {
					f.p("\t\t%s = r.Int()", field)
				} else {
					f.p("\t\t%s = %s(r.Int())", field, t)
				}
			case "uint":
				if t == "uint32" {
					f.p("\t\t%s = r.Uint()", field)
				} else {
					f.p("\t\t%s = %s(r.Uint())", field, t)
				}
			case "fixed":
				f.p("\t\t%s = r.Fixed().Float64()", field)
			case "string":
				if a.nullable() {
					f.p("\t\t%s = r.StringPtr()", field)
				} else {
					f.p("\t\t%s = r.String()", field)
				}
			case "array":
				f.p("\t\t%s = r.Array()", field)
			case "fd":
				f.p("\t\t%s = r.Fd()", field)
				fds = append(fds, field)
			case "object":
				if t == "wire.Object" {
					f.p("\t\t%s = r.Object()", field)
				} else {
					f.p("\t\t%s, _ = r.Object().(%s)", field, t)
				}
			case "new_id":
				if a.Interface == "" {
					return fmt.Errorf("%s.%s: event argument %q is an untyped new_id, which is not supported", i.Name, m.Name, a.Name)
				}
				f.p("\t\t%s = &%s{}", field, strings.TrimPrefix(t, "*"))
				f.p("\t\tr.NewObject(%s, self.Version())", field)
			}
		}
		f.p("\t\tif err := r.Err(); err != nil {")
		for _, fd := range fds {
			f.p("\t\t\twire.CloseFd(%s)", fd)
		}
		f.p("\t\t\treturn err")
		f.p("\t\t}")
		f.p("\t\tif h := self.on%s; h != nil {", camel(m.Name))
		f.p("\t\t\th(ev)")
		if len(fds) > 0 {
			f.p("\t\t} else {")
			for _, fd := range fds {
				f.p("\t\t\twire.CloseFd(%s)", fd)
			}
		}
		f.p("\t\t}")
		f.p("\t\treturn nil")
	}
	f.p("\t}")
	f.p("\treturn wire.UnknownEvent(self, opcode)")
	f.p("}")
	f.p("")
	return nil
}

// param is one Go parameter of a generated request method.
type param struct{ name, typ string }

func (g *generator) genRequest(f *file, i *iface, m *message, opcode int, claim func(name, what string) error) error {
	T := camel(i.Name)
	name := camel(m.Name)
	if err := claim(name, "request "+m.Name); err != nil {
		return err
	}

	// Split arguments into parameters and the created object.
	var params []param
	var created *arg
	createdUntyped := false
	for _, a := range m.Args {
		t, err := g.goType(a, i)
		if err != nil {
			return err
		}
		if a.Type == "new_id" {
			if created != nil {
				return fmt.Errorf("%s.%s: more than one new_id argument is not supported", i.Name, m.Name)
			}
			created = a
			if a.Interface == "" {
				createdUntyped = true
				params = append(params, param{"obj", "wire.Object"}, param{"version", "uint32"})
			}
			continue
		}
		params = append(params, param{paramName(a.Name), t})
	}
	ret := ""
	if created != nil && !createdUntyped {
		ret = "*" + camel(created.Interface)
		if _, ok := g.ifaces[created.Interface]; !ok {
			return fmt.Errorf("%s.%s: new_id interface %q is not defined by any loaded protocol", i.Name, m.Name, created.Interface)
		}
	}

	var extra []string
	var notes []string
	if m.since() > 1 {
		notes = append(notes, fmt.Sprintf("Since version %d.", m.since()))
	}
	if m.DeprecatedSince > 0 {
		notes = append(notes, fmt.Sprintf("Deprecated since version %d.", m.DeprecatedSince))
	}
	if m.Type == "destructor" {
		notes = append(notes, "This is a destructor: the proxy must not be used afterwards.")
	}
	if createdUntyped {
		notes = append(notes, "obj is bound to the new ID and must be a fresh, unbound proxy of the interface being bound; see "+
			T+camel(m.Name)+" for a typed helper.")
	}
	if ret != "" {
		notes = append(notes, "The new object has the same version as the receiver.")
	}
	if len(notes) > 0 {
		extra = notes
	}
	f.doc("", head(name+" sends the "+i.Name+"."+m.Name+" request", summaryOf(m.Description), m.Description, extra...))

	var sig []string
	for _, p := range params {
		sig = append(sig, p.name+" "+p.typ)
	}
	f.p("func (self *%s) %s(%s) %s{", T, name, strings.Join(sig, ", "), retSpace(ret))
	f.p("\tmsg := self.Begin(%d)", opcode)
	for _, a := range m.Args {
		pn := paramName(a.Name)
		t, _ := g.goType(a, i)
		switch a.Type {
		case "int":
			if t == "int32" {
				f.p("\tmsg.Int(%s)", pn)
			} else {
				f.p("\tmsg.Int(int32(%s))", pn)
			}
		case "uint":
			if t == "uint32" {
				f.p("\tmsg.Uint(%s)", pn)
			} else {
				f.p("\tmsg.Uint(uint32(%s))", pn)
			}
		case "fixed":
			f.p("\tmsg.Fixed(wire.FixedFromFloat(%s))", pn)
		case "string":
			if a.nullable() {
				f.p("\tmsg.StringPtr(%s)", pn)
			} else {
				f.p("\tmsg.String(%s)", pn)
			}
		case "array":
			f.p("\tmsg.Array(%s)", pn)
		case "fd":
			f.p("\tmsg.Fd(%s)", pn)
		case "object":
			idExpr := pn + ".ID()"
			if t == "wire.Object" {
				idExpr = pn + ".Base().ID()"
			}
			f.p("\tvar %sID uint32", pn)
			f.p("\tif %s != nil {", pn)
			f.p("\t\t%sID = %s", pn, idExpr)
			f.p("\t}")
			f.p("\tmsg.Object(%sID)", pn)
		case "new_id":
			if createdUntyped {
				f.p("\tmsg.NewObjectUntyped(obj, version)")
			} else {
				f.p("\tproxy_ := &%s{}", camel(a.Interface))
				f.p("\tmsg.NewObject(proxy_, self.Version())")
			}
		}
	}
	f.p("\tmsg.Done()")
	if m.Type == "destructor" {
		f.p("\tself.MarkDestroyed()")
	}
	if ret != "" {
		f.p("\treturn proxy_")
	}
	f.p("}")
	f.p("")

	if createdUntyped {
		return g.genBindHelper(f, i, m, params)
	}
	return nil
}

func retSpace(ret string) string {
	if ret == "" {
		return ""
	}
	return ret + " "
}

// genBindHelper emits the generic wrapper for a request with an untyped new_id
// (wl_registry.bind): it allocates the proxy of the requested type itself.
func (g *generator) genBindHelper(f *file, i *iface, m *message, params []param) error {
	T := camel(i.Name)
	fn := T + camel(m.Name)
	if err := g.claim(fn, fmt.Sprintf("bind helper for %s.%s", i.Name, m.Name)); err != nil {
		return err
	}
	recv := lowerCamel(i.Name)
	sig := []string{recv + " *" + T}
	var call []string
	for _, p := range params {
		call = append(call, p.name)
		if p.name != "obj" {
			sig = append(sig, p.name+" "+p.typ)
		}
	}
	f.p("// %s calls %s.%s with a fresh proxy of type T and returns it, for example", fn, T, camel(m.Name))
	f.p("//")
	f.p("//\tcompositor := %s[WlCompositor](registry, name, 6)", fn)
	f.p("//")
	f.p("// version must not exceed the version the compositor advertised, nor the")
	f.p("// Version constant of T's interface.")
	f.p("func %s[T any, P interface {", fn)
	f.p("\t*T")
	f.p("\twire.Object")
	f.p("}](%s) P {", strings.Join(sig, ", "))
	f.p("\tobj := P(new(T))")
	f.p("\t%s.%s(%s)", recv, camel(m.Name), strings.Join(call, ", "))
	f.p("\treturn obj")
	f.p("}")
	f.p("")
	return nil
}

