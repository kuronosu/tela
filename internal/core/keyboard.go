// Keyboard input (ARCHITECTURE section 14): platform key events become
// DOM keydown and keyup events dispatched to the focused element, with the
// default actions of the UI Events and HTML specifications.
//
// # Targets
//
// A key event targets the focused element (focus.go) and bubbles to the
// root through its primitive ancestors, like pointer events. With nothing
// focused it targets the outermost element of the content (the first one
// when the root is a fragment), as the DOM targets the body, so handlers
// on an app's outer element see the keys typed while nothing has focus.
//
// A press is a keydown (a repeat is a keydown with Repeat); a release is a
// keyup, synthetic ones included (the backend releases held keys when the
// window loses focus; their keyup runs no default action). After each
// event the queued updates are applied and the build phase runs, as after
// discrete pointer events, before the default action.
//
// # Default actions
//
// They run after the event's dispatch unless a handler called
// PreventDefault:
//
//   - keydown in a focused text field runs its key binding (typing,
//     editing, moving the caret, Enter: fieldkeys.go) first; the keys it
//     handles run no other default action;
//   - keydown Tab without Ctrl, Alt or Meta moves the focus to the next
//     element of the sequential focus order (Shift+Tab: the previous one),
//     wrapping around inside the window, or inside the focus scope that
//     contains it (focus.go);
//   - keydown Enter on a focused Button clicks it (repeats click again);
//   - keydown Space on a focused Button makes it active and its keyup
//     clicks it, unless the focus moved meanwhile, the keyup was prevented
//     or synthetic (HTML's activation behavior: Enter on keydown, Space on
//     keyup);
//   - keydown of the arrows, Page Up, Page Down, Home, End (without Ctrl,
//     Alt or Meta; Home and End also with Ctrl) and Space or Shift+Space
//     on a target that is not a Button scroll the focused scroll
//     container or the nearest one around the focus (scroll.go).
//
// A click from the keyboard is an OnClick with ClickCount 0 (the DOM's
// detail), the primary button and the key's modifiers, at the center of
// the button's border box.
//
// # focus-visible
//
// A keydown of a key that is not a modifier, without Ctrl, Alt or Meta,
// counts as keyboard interaction for the focus-visible heuristic: an
// element focused by the mouse starts matching focus-visible: when such a
// key is pressed (focus.go).

// KeyValue is a logical key (tela.Key): a W3C UI Events KeyboardEvent
// "key" value, what a browser reports as KeyboardEvent.key: a named key
// ("Enter", "Escape", "ArrowLeft", "Shift") or the character the key
// produces with the active layout and modifiers except Ctrl ("a", "A",
// "é", and " " for the space bar). Package tela declares a constant for
// every named key.
type KeyValue string

// CodeValue is a physical key (tela.Code): a W3C UI Events KeyboardEvent
// "code" value, what a browser reports as KeyboardEvent.code: the
// position on the keyboard, independent of the layout ("KeyA" is the key
// labeled A on a US keyboard, which types "q" on AZERTY), "Unidentified"
// for a key with no W3C name. Package tela declares a constant for every
// code.
type CodeValue string

// KeyLocation tells apart keys with the same meaning: the left and right
// modifiers, the numeric keypad (the DOM's KeyboardEvent.location).
type KeyLocation uint8

// The key locations, with the DOM's values.
const (
	// KeyLocationStandard is every key not listed below.
	KeyLocationStandard KeyLocation = iota
	// KeyLocationLeft is the left Shift, Control, Alt or Meta key.
	KeyLocationLeft
	// KeyLocationRight is the right Shift, Control, Alt (AltGr) or Meta key.
	KeyLocationRight
	// KeyLocationNumpad is a key of the numeric keypad.
	KeyLocationNumpad
)

// String returns "standard", "left", "right" or "numpad".
func (l KeyLocation) String() string { return platform.KeyLocation(l).String() }

// KeyboardEvent is passed to OnKeyDown and OnKeyUp (the DOM's
// KeyboardEvent). Text input does not go through it: text fields insert
// the text of the keys whose keydown no handler prevented (fieldkeys.go).
type KeyboardEvent struct {
	// Key is the logical key: "Enter", "Escape", "a", "A", " "... It
	// reflects Shift, AltGr and the lock keys, but not Ctrl: Ctrl+S has
	// Key "s" (Ctrl+Shift+S: "S").
	Key KeyValue
	// Code is the physical key ("KeyS", "Enter", "ShiftLeft"), the same
	// whatever the layout and modifiers.
	Code CodeValue
	// Location tells left and right modifiers and the numeric keypad
	// apart.
	Location KeyLocation
	// Repeat marks a keydown generated by key repeat while the key is
	// held.
	Repeat bool
	// Modifier keys held after the event (the DOM's rule: the keydown of
	// Shift has Shift set, its keyup does not); Meta is the Windows,
	// Command or Super key.
	Shift, Ctrl, Alt, Meta bool

	st *eventState
}

// StopPropagation stops the event from bubbling to the ancestors of the
// element whose handler runs. The other handlers of that element still
// run.
func (e KeyboardEvent) StopPropagation() { e.st.stop() }

// PreventDefault cancels the default action of the key: the focus move of
// Tab, the click of Enter or Space on a button.
func (e KeyboardEvent) PreventDefault() { e.st.prevent() }

// DefaultPrevented reports whether a handler called PreventDefault.
func (e KeyboardEvent) DefaultPrevented() bool { return e.st.defaultPrevented() }

// FocusEvent is passed to OnFocus and OnBlur. Like React's onFocus and
// onBlur (the DOM's focusin and focusout), focus events bubble: an
// element's OnFocus also runs when one of its descendants gains focus.
type FocusEvent struct {
	st *eventState
}

// StopPropagation stops the event from bubbling to the ancestors.
func (e FocusEvent) StopPropagation() { e.st.stop() }

// PreventDefault marks the event; focus events have no default action to
// cancel (the focus has already moved).
func (e FocusEvent) PreventDefault() { e.st.prevent() }

// DefaultPrevented reports whether a handler called PreventDefault.
func (e FocusEvent) DefaultPrevented() bool { return e.st.defaultPrevented() }

// HandleKey dispatches a platform key event (see the comment at the top of
// keyboard.go). Call it on the UI thread.
func (t *Tree) HandleKey(e platform.KeyEvent) {
	if t.root == nil {
		return
	}
	t.fixFocus()
	ke := KeyboardEvent{
		Key: KeyValue(e.Key), Code: CodeValue(e.Code.String()),
		Location: KeyLocation(e.Location), Repeat: e.Repeat,
	}
	ke.Shift, ke.Ctrl, ke.Alt, ke.Meta = modifiers(e.Mods)
	target := t.keyTarget()
	t.scr.now = max(t.scr.now, e.Time)
	if e.Action == platform.KeyPress {
		t.noteKey(e)
		st := fire(t, evKeyDown, target, ke, true)
		t.flushDiscrete()
		if !st.defaultPrevented() {
			t.keyDownDefault(target, ke, e.Text)
		}
		return
	}
	st := fire(t, evKeyUp, target, ke, true)
	t.flushDiscrete()
	t.keyUpDefault(target, ke, e.Synthetic || st.defaultPrevented())
}

// keyTarget returns the element key events target: the focused element,
// else the outermost primitive of the content, else the root.
func (t *Tree) keyTarget() *Element {
	if el := t.foc.el; el != nil && el.mounted {
		return el
	}
	var first *Element
	eachPrimitiveChild(t.root, func(c *Element) bool {
		first = c
		return false
	})
	if first != nil {
		return first
	}
	return t.root
}

// isModifierKey reports the modifier keys, which do not count as keyboard
// interaction (Chromium's IsDomKeyForModifier).
func isModifierKey(k platform.Key) bool {
	switch k {
	case platform.KeyAlt, platform.KeyAltGraph, platform.KeyCapsLock, platform.KeyControl, platform.KeyFn,
		platform.KeyFnLock, platform.KeyMeta, platform.KeyNumLock, platform.KeyScrollLock, platform.KeyShift,
		platform.KeySymbol, platform.KeySymbolLock, platform.KeyHyper, platform.KeySuper:
		return true
	}
	return false
}

// noteKey records a keydown for the focus-visible heuristic.
func (t *Tree) noteKey(e platform.KeyEvent) {
	if isModifierKey(e.Key) || e.Mods&(platform.ModCtrl|platform.ModAlt|platform.ModSuper) != 0 {
		return
	}
	t.foc.hadKey = true
	t.updateVisible()
}

// isButton reports whether el is a Button primitive.
func isButton(el *Element) bool {
	return el != nil && el.kind == elemPrimitive && el.box.kind == style.KindButton
}

func (t *Tree) keyDownDefault(target *Element, e KeyboardEvent, txt string) {
	if f := t.focusedField(); f != nil && f.el == target && t.fieldKey(f, e, txt) {
		return
	}
	switch e.Key {
	case KeyValue(platform.KeyTab):
		if !e.Ctrl && !e.Alt && !e.Meta {
			t.moveFocus(e.Shift)
		}
	case KeyValue(platform.KeyEnter):
		if el := t.foc.el; el == target && isButton(el) && t.focusable(el) {
			t.keyClick(el, e)
		}
	case " ":
		if isButton(target) {
			if el := t.foc.el; !e.Repeat && el == target && t.foc.space == nil && t.focusable(el) {
				t.foc.space = el
				el.activeN++
				t.setState(el, style.StateActive, true)
			}
			return
		}
		if !e.Ctrl && !e.Alt && !e.Meta {
			dir := float32(1)
			if e.Shift {
				dir = -1
			}
			t.keyScroll(keyPage, 1, dir)
		}
	default:
		t.keyScrollDefault(e)
	}
}

// keyScrollDefault runs the scrolling default actions of the arrows,
// Page Up, Page Down, Home and End (scroll.go).
func (t *Tree) keyScrollDefault(e KeyboardEvent) {
	if e.Alt || e.Meta {
		return
	}
	switch e.Key {
	case KeyValue(platform.KeyHome), KeyValue(platform.KeyEnd):
		dir := float32(-1)
		if e.Key == KeyValue(platform.KeyEnd) {
			dir = 1
		}
		t.keyScroll(keyEdge, 1, dir)
		return
	}
	if e.Ctrl {
		return
	}
	switch e.Key {
	case KeyValue(platform.KeyArrowUp):
		t.keyScroll(keyLine, 1, -1)
	case KeyValue(platform.KeyArrowDown):
		t.keyScroll(keyLine, 1, 1)
	case KeyValue(platform.KeyArrowLeft):
		t.keyScroll(keyLine, 0, -1)
	case KeyValue(platform.KeyArrowRight):
		t.keyScroll(keyLine, 0, 1)
	case KeyValue(platform.KeyPageUp):
		t.keyScroll(keyPage, 1, -1)
	case KeyValue(platform.KeyPageDown):
		t.keyScroll(keyPage, 1, 1)
	}
}

func (t *Tree) keyUpDefault(target *Element, e KeyboardEvent, cancelled bool) {
	if e.Key != " " {
		return
	}
	el := t.foc.space
	if el == nil {
		return
	}
	t.cancelSpace()
	if !cancelled && el == target && el == t.foc.el && el.mounted && t.focusable(el) {
		t.keyClick(el, e)
	}
}

// cancelSpace ends the Space press of a button without clicking it.
func (t *Tree) cancelSpace() {
	el := t.foc.space
	if el == nil {
		return
	}
	t.foc.space = nil
	el.activeN--
	if el.activeN <= 0 {
		el.activeN = 0
		t.setState(el, style.StateActive, false)
	}
}

// keyClick fires the click of a button activated from the keyboard.
func (t *Tree) keyClick(el *Element, e KeyboardEvent) {
	me := MouseEvent{Button: MouseButtonLeft, Shift: e.Shift, Ctrl: e.Ctrl, Alt: e.Alt, Meta: e.Meta}
	if bx := t.geomBox(el); bx != nil {
		c := windowRect(bx).Center()
		me.X, me.Y = c.X, c.Y
	}
	t.dispatchClick(el, me)
}
