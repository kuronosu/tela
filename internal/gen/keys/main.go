// Command keys generates keys_gen.go in package tela: a tela.Key constant
// for every named key of internal/platform (its Key constants) and a
// tela.Code constant for every physical key code (its KeyCode constants
// and their W3C names), so the public lists never drift from the
// platform's.
//
// It reads the platform sources (key.go and keycode.go) with go/parser
// and is run by "go generate" in the module root (see events.go there).
// The output is deterministic and gofmt'ed.
//
// Flags:
//
//	-platform dir   the internal/platform directory (default internal/platform)
//	-out path       output file (default keys_gen.go)
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

func main() {
	dir := flag.String("platform", "internal/platform", "the internal/platform directory")
	outPath := flag.String("out", "keys_gen.go", "Go file to write")
	flag.Parse()
	keySrc, err := os.ReadFile(filepath.Join(*dir, "key.go"))
	if err != nil {
		fatal(fmt.Errorf("%v (run the generator from the module root, e.g. with go generate)", err))
	}
	codeSrc, err := os.ReadFile(filepath.Join(*dir, "keycode.go"))
	if err != nil {
		fatal(err)
	}
	out, err := build(keySrc, codeSrc)
	if err != nil {
		fatal(err)
	}
	if err := os.WriteFile(*outPath, out, 0o644); err != nil {
		fatal(err)
	}
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "keys:", err)
	os.Exit(1)
}

// constant is one generated constant: its name and value, the comment of
// the group it starts (if any) and its line comment.
type constant struct {
	name, value string
	group, line string
}

// build returns the source of keys_gen.go from the sources of the
// platform's key.go and keycode.go.
func build(keySrc, codeSrc []byte) ([]byte, error) {
	keys, err := parseKeys(keySrc)
	if err != nil {
		return nil, fmt.Errorf("key.go: %v", err)
	}
	codes, err := parseCodes(codeSrc)
	if err != nil {
		return nil, fmt.Errorf("keycode.go: %v", err)
	}
	var b bytes.Buffer
	b.WriteString(`// Code generated by "go run ./internal/gen/keys" from internal/platform; DO NOT EDIT.

package tela

// Named keys: the values of KeyboardEvent.Key that are not characters
// (W3C UI Events KeyboardEvent key values, https://www.w3.org/TR/uievents-key/).
// A key that produces a character has that character as its Key ("a",
// "A", "1", "é", and " " for the space bar), so compare with a string
// literal: e.Key == "z". Key is a string type: e.Key == "Enter" and
// e.Key == tela.KeyEnter mean the same.
const (
`)
	write(&b, keys, "Key")
	b.WriteString(`)

// Physical key codes: the values of KeyboardEvent.Code (W3C UI Events
// KeyboardEvent code values, https://www.w3.org/TR/uievents-code/), the
// position of the key whatever the layout: CodeKeyA is the key labeled A
// on a US keyboard (it types "q" on AZERTY). Code is a string type:
// e.Code == "KeyS" and e.Code == tela.CodeKeyS mean the same.
const (
`)
	write(&b, codes, "Code")
	b.WriteString(")\n")
	return format.Source(b.Bytes())
}

func write(b *bytes.Buffer, cs []constant, typ string) {
	for i, c := range cs {
		if c.group != "" {
			if i > 0 {
				b.WriteByte('\n')
			}
			for _, l := range strings.Split(strings.TrimSpace(c.group), "\n") {
				fmt.Fprintf(b, "\t// %s\n", strings.TrimSpace(l))
			}
		}
		fmt.Fprintf(b, "\t%s %s = %s", c.name, typ, strconv.Quote(c.value))
		if c.line != "" {
			fmt.Fprintf(b, " // %s", strings.TrimSpace(c.line))
		}
		b.WriteByte('\n')
	}
}

// parseKeys returns the string constants of type Key in key.go, in
// order.
func parseKeys(src []byte) ([]constant, error) {
	f, err := parser.ParseFile(token.NewFileSet(), "key.go", src, parser.ParseComments)
	if err != nil {
		return nil, err
	}
	var out []constant
	for _, d := range f.Decls {
		g, ok := d.(*ast.GenDecl)
		if !ok || g.Tok != token.CONST {
			continue
		}
		for _, s := range g.Specs {
			vs := s.(*ast.ValueSpec)
			if id, ok := vs.Type.(*ast.Ident); !ok || id.Name != "Key" || len(vs.Values) != len(vs.Names) {
				continue
			}
			for i, n := range vs.Names {
				lit, ok := vs.Values[i].(*ast.BasicLit)
				if !ok || lit.Kind != token.STRING {
					return nil, fmt.Errorf("%s is not a string literal", n.Name)
				}
				v, err := strconv.Unquote(lit.Value)
				if err != nil {
					return nil, err
				}
				if n.Name != "Key"+v {
					return nil, fmt.Errorf("%s has the value %q; the generator expects Key<value>", n.Name, v)
				}
				c := constant{name: n.Name, value: v, group: publicDoc(docText(vs.Doc)), line: docText(vs.Comment)}
				if n.Name == "KeyUnidentified" {
					c.group = "KeyUnidentified is a key with neither a name nor a character."
				}
				out = append(out, c)
			}
		}
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("no Key constants found")
	}
	return out, nil
}

// parseCodes returns the KeyCode constants of keycode.go, in order, with
// their W3C names from the keyCodeNames table.
func parseCodes(src []byte) ([]constant, error) {
	f, err := parser.ParseFile(token.NewFileSet(), "keycode.go", src, parser.ParseComments)
	if err != nil {
		return nil, err
	}
	names := map[string]string{}
	for _, d := range f.Decls {
		g, ok := d.(*ast.GenDecl)
		if !ok || g.Tok != token.VAR {
			continue
		}
		for _, s := range g.Specs {
			vs := s.(*ast.ValueSpec)
			if len(vs.Names) != 1 || vs.Names[0].Name != "keyCodeNames" || len(vs.Values) != 1 {
				continue
			}
			lit, ok := vs.Values[0].(*ast.CompositeLit)
			if !ok {
				return nil, fmt.Errorf("keyCodeNames is not a composite literal")
			}
			for _, e := range lit.Elts {
				kv, ok := e.(*ast.KeyValueExpr)
				if !ok {
					return nil, fmt.Errorf("keyCodeNames has an element without a key")
				}
				id, ok1 := kv.Key.(*ast.Ident)
				bl, ok2 := kv.Value.(*ast.BasicLit)
				if !ok1 || !ok2 || bl.Kind != token.STRING {
					return nil, fmt.Errorf("unexpected keyCodeNames element")
				}
				v, err := strconv.Unquote(bl.Value)
				if err != nil {
					return nil, err
				}
				names[id.Name] = v
			}
		}
	}
	if len(names) == 0 {
		return nil, fmt.Errorf("keyCodeNames not found")
	}
	var out []constant
	for _, d := range f.Decls {
		g, ok := d.(*ast.GenDecl)
		if !ok || g.Tok != token.CONST {
			continue
		}
		iota := false
		for _, s := range g.Specs {
			vs := s.(*ast.ValueSpec)
			if id, ok := vs.Type.(*ast.Ident); ok && id.Name == "KeyCode" && len(vs.Values) == 1 {
				if v, ok := vs.Values[0].(*ast.Ident); ok && v.Name == "iota" {
					iota = true
				}
			}
			if !iota {
				continue
			}
			for _, n := range vs.Names {
				if n.Name == "numKeyCodes" {
					continue
				}
				v, ok := names[n.Name]
				if !ok {
					return nil, fmt.Errorf("%s has no name in keyCodeNames", n.Name)
				}
				if n.Name != "Code"+v {
					return nil, fmt.Errorf("%s is named %q; the generator expects Code<name>", n.Name, v)
				}
				c := constant{name: n.Name, value: v, line: docText(vs.Comment)}
				if n.Name != "CodeUnidentified" {
					c.group = docText(vs.Doc)
				} else {
					c.group = "CodeUnidentified is a key without a W3C code value."
				}
				out = append(out, c)
				delete(names, n.Name)
			}
		}
		if iota {
			break
		}
	}
	if len(names) > 0 {
		return nil, fmt.Errorf("keyCodeNames has names without constants: %v", names)
	}
	return out, nil
}

// publicDoc rewrites the parts of the platform's comments that name
// platform fields the public KeyboardEvent does not have.
func publicDoc(s string) string {
	return strings.ReplaceAll(s, "the next key's Text carries the result", "the next key types the result")
}

func docText(g *ast.CommentGroup) string {
	if g == nil {
		return ""
	}
	return g.Text()
}
