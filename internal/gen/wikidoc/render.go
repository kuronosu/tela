package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/doc"
	"go/printer"
	"go/token"
	"sort"
	"strings"
	"unicode"
)

// anchorOf returns the anchor GitHub gives a heading: lower case, spaces
// as hyphens, punctuation removed.
func anchorOf(heading string) string {
	var sb strings.Builder
	for _, r := range strings.ToLower(heading) {
		switch {
		case r == ' ':
			sb.WriteByte('-')
		case r == '-' || r == '_' || unicode.IsLetter(r) || unicode.IsDigit(r):
			sb.WriteRune(r)
		}
	}
	return sb.String()
}

// Heading levels of the page.
const (
	levelSection = 2 // Overview, Index, Constants, Functions, Types
	levelSymbol  = 3 // a function or a type
	levelMember  = 4 // a method or a constructor of a type
	levelDocSym  = 5 // headings inside the doc comment of a symbol
	levelDocPkg  = 3 // headings inside the package comment
)

// pageWriter writes one page.
type pageWriter struct {
	g        *generator
	p        *pkgInfo
	md       *mdWriter
	sb       strings.Builder
	headings map[string]string // anchor -> heading text
	err      error
}

func (g *generator) render(p *pkgInfo) ([]byte, error) {
	w := &pageWriter{g: g, p: p, headings: map[string]string{}}
	w.md = &mdWriter{g: g, cur: p, note: func(_ int, text string) { w.noteHeading(text) }}
	w.page()
	if w.err != nil {
		return nil, w.err
	}
	return []byte(w.sb.String()), nil
}

// noteHeading registers a heading, failing on a duplicate anchor, which
// would send links to the wrong place.
func (w *pageWriter) noteHeading(text string) {
	a := anchorOf(text)
	if prev, dup := w.headings[a]; dup && w.err == nil {
		w.err = fmt.Errorf("headings %q and %q have the same anchor #%s", prev, text, a)
	}
	w.headings[a] = text
}

func (w *pageWriter) heading(level int, text string) {
	w.noteHeading(text)
	w.sb.WriteString(strings.Repeat("#", level) + " " + text + "\n\n")
}

func (w *pageWriter) para(s string) { w.sb.WriteString(s + "\n\n") }

// docText writes a doc comment as Markdown followed by a blank line.
func (w *pageWriter) docText(text string, level int) {
	if md := w.md.convert(text, level); md != "" {
		w.sb.WriteString(md + "\n")
	}
}

// code writes a fenced Go code block.
func (w *pageWriter) code(src string) {
	w.sb.WriteString(fence("go", detab(src)) + "\n")
}

// printNode formats an AST node as gofmt would.
func (w *pageWriter) printNode(fset *token.FileSet, n any) string {
	var buf bytes.Buffer
	cfg := printer.Config{Mode: printer.UseSpaces | printer.TabIndent, Tabwidth: 8}
	if err := cfg.Fprint(&buf, fset, n); err != nil && w.err == nil {
		w.err = err
	}
	return strings.TrimRight(buf.String(), "\n")
}

func (w *pageWriter) page() {
	p, d := w.p, w.p.doc
	fmt.Fprintf(&w.sb, "<!-- Code generated by \"go run ./internal/gen/wikidoc\"; DO NOT EDIT. -->\n\n")
	w.noteHeading("API reference: package " + d.Name)
	fmt.Fprintf(&w.sb, "# API reference: package `%s`\n\n", d.Name)
	w.code(fmt.Sprintf("import %q", p.spec.ImportPath))
	w.para(fmt.Sprintf("This page is generated from the doc comments of the package; the same text is on "+
		"[pkg.go.dev](https://pkg.go.dev/%s). For guides and examples, start at the [wiki home](Home).", p.spec.ImportPath))

	w.index()

	w.heading(levelSection, "Overview")
	w.docText(d.Doc, levelDocPkg)
	w.examples(d.Examples, levelSymbol)

	if len(d.Consts) > 0 {
		w.heading(levelSection, "Constants")
		for _, v := range d.Consts {
			w.value(v)
		}
	}
	if len(d.Vars) > 0 {
		w.heading(levelSection, "Variables")
		for _, v := range d.Vars {
			w.value(v)
		}
	}
	if len(d.Funcs) > 0 {
		w.heading(levelSection, "Functions")
		for _, f := range d.Funcs {
			w.function(f, levelSymbol, w.p.funcTitle(f))
		}
	}
	if len(d.Types) > 0 {
		w.heading(levelSection, "Types")
		for _, t := range d.Types {
			w.typ(t)
		}
	}
	s := tidy(w.sb.String())
	w.sb.Reset()
	w.sb.WriteString(s)
}

// tidy collapses runs of blank lines outside code blocks to one, and
// ends the page with a single newline.
func tidy(s string) string {
	var out []string
	fence := ""
	for _, line := range strings.Split(s, "\n") {
		trimmed := strings.TrimLeft(line, "`")
		ticks := line[:len(line)-len(trimmed)]
		switch {
		case fence == "" && len(ticks) >= 3:
			fence = ticks
		case fence != "" && len(ticks) >= len(fence) && trimmed == "":
			fence = ""
		}
		if fence == "" && line == "" && len(out) > 0 && out[len(out)-1] == "" {
			continue
		}
		out = append(out, line)
	}
	return strings.TrimRight(strings.Join(out, "\n"), "\n") + "\n"
}

// link returns a Markdown link to an anchor of this page.
func link(text, anchor string) string { return "[`" + text + "`](#" + anchor + ")" }

// index writes the table of contents.
func (w *pageWriter) index() {
	d := w.p.doc
	w.noteHeading("Index")
	w.sb.WriteString("## Index\n\n")
	w.sb.WriteString("- [Overview](#overview)\n")
	if len(d.Consts) > 0 {
		w.sb.WriteString("- [Constants](#constants)\n")
	}
	if len(d.Vars) > 0 {
		w.sb.WriteString("- [Variables](#variables)\n")
	}
	// Every function, those go/doc groups under the type they return
	// (UseState under Setter) included: they are what people look for.
	funcs := append([]*doc.Func(nil), d.Funcs...)
	for _, t := range d.Types {
		funcs = append(funcs, t.Funcs...)
	}
	sort.SliceStable(funcs, func(i, j int) bool { return funcs[i].Name < funcs[j].Name })
	if len(funcs) > 0 {
		var names []string
		for _, f := range funcs {
			names = append(names, link(f.Name, anchorOf(w.p.funcTitle(f))))
		}
		label := "Functions"
		if len(d.Funcs) > 0 {
			label = "[Functions](#functions)"
		}
		w.sb.WriteString("- " + label + ": " + strings.Join(names, " · ") + "\n")
	}
	if len(d.Types) > 0 {
		w.sb.WriteString("- [Types](#types)\n")
		for _, t := range d.Types {
			line := "  - " + link("type "+t.Name, anchorOf("type "+t.Name))
			var members []string
			for _, f := range t.Funcs {
				members = append(members, link(f.Name, anchorOf(w.p.funcTitle(f))))
			}
			for _, m := range w.methods(t) {
				members = append(members, link(m.Name, anchorOf("func ("+m.Recv+") "+m.Name)))
			}
			if len(members) > 0 {
				line += ": " + strings.Join(members, " · ")
			}
			w.sb.WriteString(line + "\n")
		}
	}
	w.sb.WriteString("\n")
}

// methods returns the methods of t, those of the type an alias points to
// included.
func (w *pageWriter) methods(t *doc.Type) []*doc.Func {
	ms := t.Methods
	if a := w.p.aliases[t.Name]; a != nil {
		ms = append(append([]*doc.Func(nil), ms...), a.typ.Methods...)
		sort.SliceStable(ms, func(i, j int) bool { return ms[i].Name < ms[j].Name })
	}
	return ms
}

// value writes a group of constants or variables.
func (w *pageWriter) value(v *doc.Value) {
	w.code(w.printNode(w.p.fset, v.Decl))
	w.docText(v.Doc, levelDocSym)
}

// function writes a function or method with its documentation and examples.
func (w *pageWriter) function(f *doc.Func, level int, title string) {
	w.heading(level, title)
	w.code(w.printNode(w.p.fset, f.Decl))
	w.docText(f.Doc, levelDocSym)
	w.examples(f.Examples, level+1)
}

// typ writes a type section.
func (w *pageWriter) typ(t *doc.Type) {
	p := w.p
	w.heading(levelSymbol, "type "+t.Name)
	w.code(w.printNode(p.fset, t.Decl))
	a := p.aliases[t.Name]
	text := t.Doc
	if text == "" && a != nil {
		text = a.typ.Doc
	}
	w.docText(text, levelDocSym)
	if a != nil {
		w.para(fmt.Sprintf("`%s` is an alias of `%s`, declared in an internal package of the module. "+
			"pkg.go.dev shows only the alias; the exported fields and methods of the aliased type, listed here, are part of the API:", t.Name, a.target))
		w.code(w.printNode(a.pkg.fset, a.typ.Decl))
		for _, v := range append(append([]*doc.Value(nil), a.typ.Consts...), a.typ.Vars...) {
			w.value(v)
		}
	}
	for _, v := range t.Consts {
		w.value(v)
	}
	for _, v := range t.Vars {
		w.value(v)
	}
	w.examples(t.Examples, levelMember)
	for _, f := range t.Funcs {
		w.function(f, levelMember, w.p.funcTitle(f))
	}
	for _, m := range w.methods(t) {
		fset := p.fset
		if isForeign(t, a, m) {
			fset = a.pkg.fset
		}
		w.methodFn(m, fset)
	}
}

// isForeign reports whether m is a method of the aliased type.
func isForeign(t *doc.Type, a *alias, m *doc.Func) bool {
	if a == nil {
		return false
	}
	for _, am := range a.typ.Methods {
		if am == m {
			return true
		}
	}
	return false
}

func (w *pageWriter) methodFn(m *doc.Func, fset *token.FileSet) {
	title := "func (" + m.Recv + ") " + m.Name
	w.heading(levelMember, title)
	w.code(w.printNode(fset, m.Decl))
	w.docText(m.Doc, levelDocSym)
	w.examples(m.Examples, levelMember+1)
}

// examples writes the runnable examples of a symbol.
func (w *pageWriter) examples(exs []*doc.Example, level int) {
	for _, e := range exs {
		title := "Example"
		if e.Suffix != "" {
			title += " (" + e.Suffix + ")"
		}
		w.para("**" + title + "**")
		w.docText(e.Doc, levelDocSym)
		body := w.exampleBody(e)
		if body != "" {
			w.code(body)
		}
	}
}

// exampleBody returns the statements of an example function, indented
// as in the file but for one level.
func (w *pageWriter) exampleBody(e *doc.Example) string {
	src := w.printNode(w.p.fset, &printer.CommentedNode{Node: e.Code, Comments: e.Comments})
	if _, ok := e.Code.(*ast.BlockStmt); !ok {
		return src
	}
	lines := strings.Split(src, "\n")
	if len(lines) < 2 {
		return ""
	}
	lines = lines[1 : len(lines)-1] // the braces
	for i, l := range lines {
		lines[i] = strings.TrimPrefix(l, "\t")
	}
	return strings.Join(lines, "\n")
}
